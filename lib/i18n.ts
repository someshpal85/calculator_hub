const DICTS: Record<Locale, Partial<Dict>> = { en, hi, es, fr, de, zh, pt, ru, ja, tr };

export function t(key: string, locale: Locale = "en", vars?: Record<string, string | number>): string {
  let s = DICTS[locale][key] ?? en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  }
  return s;
}

/** Localized category display name; falls back to English name. */
export function categoryName(slug: string, locale: Locale = "en", fallback = slug): string {
  return t(`cat.${slug}`, locale) === `cat.${slug}` ? fallback : t(`cat.${slug}`, locale);
}
